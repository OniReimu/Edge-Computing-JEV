"""Every number the manuscript quotes from RQ1-RQ4, computed from cells.csv / comms.csv / hypotheses.csv."""
import pandas as pd
c = pd.read_csv("cells.csv"); m = pd.read_csv("comms.csv")
J, D, G, Q = "Jev-1.13.0", "DeepSeek-V4.1-Flash", "GLM-5.3-Flash", "Qwen3.8-Flash"
H = [J, D, G, Q]
out = []
def w(k, v): out.append(f"| {k} | {v} |")
main = c[c.model.isin(H)]
w("conditions (hosted, RQ1a..RQ4)", main[main.model == J].shape[0])
p50 = main.pivot_table(index=["rq", "condition"], columns="model", values="latency_p50")
for x in (D, G, Q):
    r = 100 * (1 - p50[J] / p50[x]); w(f"p50 reduction vs {x} min-max %", f"{r.min():.1f}-{r.max():.1f}")
w("Jev p50 min-max s", f"{p50[J].min():.3f}-{p50[J].max():.3f}")
em = main.pivot_table(index=["rq", "condition"], columns="model", values="em")
four = [("RQ1a", k) for k in ["base", "pad_512", "pad_2048", "pad_8192", "pad_16384"]] + \
       [("RQ2", k) for k in ["clean", "codeswitch", "colloquial", "keyvalue", "negation", "noise", "revised"]] + \
       [("RQ3", k) for k in ["F4_low", "F4_medium", "F4_high"]]
g = 100 * (em.loc[four, D] - em.loc[four, J]); w("EM gap DeepSeek-Jev, 4-field (excl defaultbait) pp", f"{g.min():.1f}-{g.max():.1f} (n={len(g)})")
f8 = [("RQ3", k) for k in ["F8_low", "F8_medium", "F8_high"]]
g8 = 100 * (em.loc[f8, D] - em.loc[f8, J]); w("EM gap DeepSeek-Jev, F8 pp", f"{g8.min():.1f}-{g8.max():.1f}")
w("Jev EM F8 min-max", f"{em.loc[f8, J].min():.3f}-{em.loc[f8, J].max():.3f}")
w("DeepSeek EM F8 min-max", f"{em.loc[f8, D].min():.3f}-{em.loc[f8, D].max():.3f}")
cost = main.pivot_table(index=["rq", "condition"], columns="model", values="cost_usd_per_1000_correct")
lower = cost[J] < cost[D]; w("conditions Jev cost/1000 correct < DeepSeek", f"{lower.sum()}/{len(lower)}; higher: {list(cost.index[~lower])}")
r = 100 * (1 - cost.loc[lower, J] / cost.loc[lower, D]); w("cost reduction vs DeepSeek where lower %", f"{r.min():.1f}-{r.max():.1f}")
r4 = 100 * (1 - cost.loc[four, J] / cost.loc[four, D]); w("cost reduction vs DeepSeek, 4-field set %", f"{r4.min():.1f}-{r4.max():.1f}")
for x in (G, Q):
    lw = cost[J] < cost[x]; w(f"conditions Jev cost < {x}", f"{lw.sum()}/{len(lw)}")
for x in H:
    w(f"RQ1a p50 base->16K {x} s", f"{p50.loc[('RQ1a','base'), x]:.3f}->{p50.loc[('RQ1a','pad_16384'), x]:.3f}")
    w(f"RQ1b p50 k1->k8 {x} s", f"{p50.loc[('RQ1b','k1'), x]:.3f}->{p50.loc[('RQ1b','k8'), x]:.3f}")
    w(f"RQ3 p50 F4..F8 range {x} s", f"{p50.loc[[k for k in p50.index if k[0]=='RQ3'], x].min():.3f}-{p50.loc[[k for k in p50.index if k[0]=='RQ3'], x].max():.3f}")
    w(f"RQ4 p50 range {x} s", f"{p50.loc[[k for k in p50.index if k[0]=='RQ4'], x].min():.3f}-{p50.loc[[k for k in p50.index if k[0]=='RQ4'], x].max():.3f}")
hy = pd.read_csv("hypotheses.csv")
w("hypotheses.csv columns", ",".join(hy.columns))
rq2 = c[(c.rq == "RQ2") & c.model.isin(H + ["SemIf-Qwen3.5-4B", "Laya"])]
for x in H + ["SemIf-Qwen3.5-4B", "Laya"]:
    s = rq2[rq2.model == x].set_index("condition")
    w(f"RQ2 EM {x} clean/defaultbait", f"{s.loc['clean','em']:.3f}/{s.loc['defaultbait','em']:.3f}")
    w(f"RQ2 unsafe {x} min-max", f"{s.unsafe_rate.min():.3f}-{s.unsafe_rate.max():.3f}; defaultbait {s.loc['defaultbait','unsafe_rate']:.3f}")
    w(f"RQ2 spurious {x} min-max", f"{s.spurious_rate.min():.3f}-{s.spurious_rate.max():.3f}")
tok = c[(c.rq == "RQ3")].pivot_table(index="condition", columns="model", values="output_tokens_median")
for x in H: w(f"RQ3 output tokens F4 med / F8 med {x}", f"{tok.loc['F4_medium', x]} / {tok.loc['F8_medium', x]}")
r4c = c[c.rq == "RQ4"]
for x in H + ["SemIf-Qwen3.5-4B", "Laya", "Qwen3.5-4B-JSON", "MiniLM-Reranker", "DistilBERT-Clf-All"]:
    s = r4c[r4c.model == x].set_index("condition")
    w(f"RQ4 {x} seen/unseen/unsF1 by K", "; ".join(f"{k}:{s.loc[k,'seen_top1']:.3f}/{s.loc[k,'unseen_top1']:.3f}/{s.loc[k,'unsupported_f1']:.3f}" for k in s.index))
cm = m[(m.rq == "RQ2") & (m.condition == "clean")].set_index("model")
for x in H + ["SemIf-Qwen3.5-4B", "Laya", "Qwen3.5-4B-JSON"]:
    w(f"RQ2 clean comms {x}", f"IQR {cm.loc[x,'jitter_iqr_s']*1000:.1f} ms; P(>0.5s) {cm.loc[x,'p_gt_0_500']:.3f}; P(>1s) {cm.loc[x,'p_gt_1_000']:.3f}; J/decision {cm.loc[x,'energy_j_per_decision']}")
open("paper_numbers.md", "w").write("# Numbers quoted in the manuscript (RQ1-RQ4)\n\nGenerated by paper_numbers.py from cells.csv, comms.csv.\n\n| quantity | value |\n|---|---|\n" + "\n".join(out) + "\n")
print("\n".join(out))
